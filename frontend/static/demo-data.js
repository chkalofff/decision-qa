// Подкладывает демо-результаты пакета: файлы помечаются «ok», результаты и
// длительности разложены по id файлов (сопоставление по имени), правила
// решения снапшотятся в state.batch.decision — как после настоящего прогона.
export function applyDemoBatchResults() {
  state.batch.decision = state.decision && state.decision.enabled !== false &&
    state.decision.outcomes && state.decision.outcomes.length
    ? JSON.parse(JSON.stringify(state.decision)) : null;
  for (const f of state.batch.files) {
    const demo = RESUME_ANSWERS[f.name];
    if (!demo) continue;
    state.batch.results[f.id] = {
      [DEMO_MODEL_KEY]: {
        ok: true,
        answers: demo.answers,
        usage: { prompt_tokens: 1900 },
        metrics: { duration_s: demo.duration, prompt_tokens: 1900, prefill_tok_s: 136.9, mode: "decisions" },
        prompt_format_version: 1,
      },
    };
    state.batch.durations[f.id] = demo.duration;
    f.status = "ok";
  }
}
