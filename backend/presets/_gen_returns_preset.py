def jpeg_data_url(path: Path) -> str:
    return "data:image/jpeg;base64," + base64.b64encode(path.read_bytes()).decode()


def main() -> None:
    files = []
    for name, content, photos in FILES:
        entry = {"name": name, "content": content.strip()}
        if photos:
            entry["images"] = [jpeg_data_url(PHOTOS_DIR / p) for p in photos]
        files.append(entry)
    preset = {
        "name": "Возвраты: претензии с фото",
        "description": "5 претензий на возврат с фото (0–3) × дефект, обоснованность, риск (vision)",
        "page": "batch",
        "questions": QUESTIONS,
        "files": files,
    }
    path = OUT_DIR / "batch_returns_claims.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(preset, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"batch_returns_claims.json: {path.stat().st_size / 1024:.1f} КБ")


if __name__ == "__main__":
    main()
