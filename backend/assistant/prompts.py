def serialize_snapshot(snapshot: dict | None) -> str:
    if not snapshot:
        return "(состояние не передано)"
    text = json.dumps(snapshot, ensure_ascii=False, default=str)
    if len(text) > _MAX_SNAPSHOT_CHARS:
        text = text[:_MAX_SNAPSHOT_CHARS] + "… (обрезано)"
    return text
